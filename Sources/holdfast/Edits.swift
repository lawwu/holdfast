import Foundation

// MARK: - Changes asked for in Ask
//
// "Mark the 401(k) item done", "add today's visit to the dentist log": the answer model reads the
// note and calls propose_edit with the exact text to replace. Nothing in the vault changes then.
// The change waits in the Inbox as a proposal showing what would change; approving it writes the
// note (a copy is kept first, and undo puts it back), the same way a filed document is approved.
// Several changes to one note in one conversation build on each other in a single proposal.

enum Edits {
    /// Notes the model may propose changes to. CSV tables take new rows through filing instead.
    static let editable: Set<String> = ["md", "txt"]
    /// Lines of unchanged text shown around each change in the Inbox.
    static let context = 1

    /// A pending change to `target` already in the Inbox, if any: a second change builds on it.
    static func pending(for target: String) -> Note? {
        inbox().first { $0.meta["kind"] == "filing" && $0.meta["action"] == "edit" && $0.meta["target"] == target }
    }

    /// Files a proposal for one change to a note and returns a short description for the model.
    /// `old` empty: `new` is added at the end of the note.
    @discardableResult
    static func propose(path raw: String, old: String, new: String, why: String, by: String) throws -> String {
        let path = raw.trimmingCharacters(in: CharacterSet(charactersIn: "/ "))
        let url = try Drop.safeTarget(path)
        guard editable.contains(url.pathExtension.lowercased()) else {
            throw HoldfastError("only notes (.md, .txt) can be changed this way; \(path) isn't one")
        }
        guard let file = try? String(contentsOf: url, encoding: .utf8) else {
            throw HoldfastError("no note at \(path); use list_folder to find it (new notes come in through the drop folder)")
        }
        if file.split(separator: "\n", omittingEmptySubsequences: false).prefix(12).contains(where: { $0.hasPrefix("> GENERATED") }) {
            throw HoldfastError("\(path) is generated by a script; change the script and regenerate it instead")
        }
        let existing = pending(for: path)
        let current = existing?.body ?? file
        let updated: String
        if old.isEmpty {
            let add = new.trimmingCharacters(in: .newlines)
            guard !add.isEmpty else { throw HoldfastError("nothing to add") }
            updated = current.trimmingCharacters(in: .newlines) + "\n\n" + add + "\n"
        } else {
            var find = old
            var count = current.components(separatedBy: find).count - 1
            if count == 0 {  // the model often drops or adds whitespace at the ends
                find = old.trimmingCharacters(in: .whitespacesAndNewlines)
                count = find.isEmpty ? 0 : current.components(separatedBy: find).count - 1
            }
            guard count > 0 else {
                throw HoldfastError("that text isn't in \(path); read_note it and copy the line exactly, including any - [ ] and **")
            }
            guard count == 1 else {
                throw HoldfastError("that text is in \(path) \(count) times; include more of the line so it matches once")
            }
            let r = current.range(of: find)!
            updated = current.replacingCharacters(in: r, with: old == find ? new : new.trimmingCharacters(in: .whitespacesAndNewlines))
        }
        guard updated != current else { throw HoldfastError("that change leaves \(path) as it is") }

        let today = Drop.dayString(holdfast.today())
        let name = (path as NSString).lastPathComponent
        var meta = existing?.meta ?? ["kind": "filing", "action": "edit", "target": path, "proposed_by": by,
                                      "base_hash": FilingLog.hash(file), "title": "Change \(name)"]
        meta["proposed"] = today
        let why = why.trimmingCharacters(in: .whitespacesAndNewlines)
        if !why.isEmpty { meta["why"] = [meta["why"], why].compactMap { $0 }.joined(separator: " · ") }
        let added = diff(file, updated).filter { $0.kind == "+" }.map(\.text).joined(separator: "\n")
        let flags = privacyFlags(added, names: Profile.isCounseling(path))
        meta["privacy_flags"] = flags.isEmpty ? nil : flags.joined(separator: "; ")
        let slug = slugify(name).isEmpty ? "edit" : slugify(name)
        let at = existing?.path ?? Drop.unique(Config.inboxDir.appendingPathComponent("\(today.replacingOccurrences(of: "-", with: ""))-edit-\(slug).md"), ifExists: true)
        try Note(path: at, meta: meta, body: updated).write()
        let shown = diff(file, updated).filter { $0.kind != " " }.prefix(12).map { "\($0.kind) \($0.text)" }.joined(separator: "\n")
        return "Proposed a change to \(path) for the user to approve in the Inbox (nothing is changed until then):\n\(shown)"
    }

    struct Line: Hashable { let kind: Character; let text: String }  // "+", "-", " " (unchanged), "…" (skipped)

    /// The changed lines with `context` unchanged lines around them; long unchanged runs become "…".
    static func diff(_ a: String, _ b: String) -> [Line] {
        let old = a.components(separatedBy: "\n"), new = b.components(separatedBy: "\n")
        let d = new.difference(from: old)
        var removed = Set<Int>(), inserted = Set<Int>()
        for c in d {
            switch c {
            case .remove(let o, _, _): removed.insert(o)
            case .insert(let o, _, _): inserted.insert(o)
            }
        }
        // Walk both files together, unchanged lines in step.
        var all: [Line] = []
        var i = 0, j = 0
        while i < old.count || j < new.count {
            if i < old.count, removed.contains(i) { all.append(Line(kind: "-", text: old[i])); i += 1 }
            else if j < new.count, inserted.contains(j) { all.append(Line(kind: "+", text: new[j])); j += 1 }
            else { if j < new.count { all.append(Line(kind: " ", text: new[j])) }; i += 1; j += 1 }
        }
        let changed = all.indices.filter { all[$0].kind != " " }
        var keep = Set<Int>()
        for k in changed { for n in max(0, k - context)...min(all.count - 1, k + context) { keep.insert(n) } }
        var out: [Line] = []
        for k in all.indices {
            if keep.contains(k) { out.append(all[k]) }
            else if out.last?.kind != "…" { out.append(Line(kind: "…", text: "")) }
        }
        if out.last?.kind == "…" { out.removeLast() }
        if out.first?.kind == "…" { out.removeFirst() }
        return out
    }

    /// Writes an approved change (the caller holds the write lock). Refused when the note changed
    /// after the proposal, so an edit made elsewhere is never overwritten.
    static func apply(_ item: Note, at dest: URL, target: String) throws -> URL {
        guard let now = try? String(contentsOf: dest, encoding: .utf8) else {
            throw HoldfastError("\(target) was moved or deleted after this change was proposed")
        }
        if let base = item.meta["base_hash"], FilingLog.hash(now) != base {
            throw HoldfastError("\(target) changed after this change was proposed; reject it and ask again")
        }
        let before = Versions.snapshot(dest, reason: "edit")
        try item.body.write(to: dest, atomically: true, encoding: .utf8)
        let added = diff(now, item.body).filter { $0.kind == "+" }.map(\.text).joined(separator: "\n")
        FilingLog.add(FilingRecord(title: item.meta["title"] ?? target, target: target, action: "edit", original: nil,
                                   snapshot: before?.path, after: FilingLog.hash(item.body), addition: added,
                                   proposal: item.meta, proposalBody: item.body, rule: nil))
        return dest
    }
}
