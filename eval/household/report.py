"""Metrics for the household fixture, one row per model run.

Reads eval/household/results/qa/*.json (from `mackb eval`) and
eval/household/results/filing/*.json (from `mackb eval-filing`) and writes
eval/household/report.md. Stdlib only; no LLM judge, so reruns are comparable.

  python3 eval/household/report.py

Q&A metrics (per run):
- Facts: share of expected-fact regexes found in the answer (answerable questions)
- Abstain: unanswerable questions where the answer says it isn't in the vault
- Context: share of expected facts present in the passages the model was given
- Files: share of the files holding the answer that were among those passages
- Cited: answers that cite at least one passage as [n]
Filing metrics (per run): right action (new/append/skip), right place (path
regex), facts kept, leaks (forbidden ids or full names saved), errors.
"""
import json, pathlib, statistics

import os
# The fixture: this folder, or another with the same layout (MACKB_FIXTURE=eval/household-hard).
HERE = pathlib.Path(os.environ.get("MACKB_FIXTURE") or pathlib.Path(__file__).parent).resolve()
RES = HERE / "results"


def load(kind):
    d = RES / kind
    return {p.stem: json.loads(p.read_text()) for p in sorted(d.glob("*.json"))} if d.exists() else {}


def pct(x):
    return "—" if x is None else f"{x * 100:.0f}%"


def mean(xs):
    xs = [x for x in xs if x is not None]
    return statistics.mean(xs) if xs else None


def median(xs):
    xs = [x for x in xs if x is not None]
    return statistics.median(xs) if xs else None


def qa_summary(rs):
    ans = [r for r in rs if r["kind"] != "unanswerable"]
    un = [r for r in rs if r["kind"] == "unanswerable"]
    gen = [r for r in rs if r.get("outputTokens")]
    toks = sum(r["outputTokens"] for r in gen)
    gen_s = sum(r["outputTokens"] / max(r["tokPerSec"], 0.001) for r in gen)
    return {
        "facts": mean(r["facts"] for r in ans),
        "abstain": mean(r["facts"] for r in un) if un else None,
        "context": mean(r.get("contextRecall") for r in ans),
        "files": mean(r.get("pathRecall") for r in ans),
        "cited": mean(1.0 if r["cited"] else 0.0 for r in ans),
        "median_s": median(r["seconds"] for r in rs),
        "total_min": sum(r["seconds"] for r in rs) / 60,
        "tok_s": toks / gen_s if gen_s else None,
    }


out = ["# Household fixture — model comparison", "",
       "Synthetic vault (`vault/`), today fixed at 2026-11-05. Generated by `report.py`; "
       "see `README.md` for how each number is scored.", ""]

qa = load("qa")
# Re-score answers against the current questions.json, so a fixed pattern
# applies to saved runs without asking the models again.
import re
QS = {q["id"]: q for q in json.loads((HERE / "questions.json").read_text())}
for rs in qa.values():
    for r in rs:
        q = QS.get(r["id"])
        if q and r.get("mode") != "retrieval":
            hits = [p for p in q["expect"] if re.search(p, r["answer"], re.I)]
            r["facts"] = len(hits) / max(len(q["expect"]), 1)
            # A wrong-answer signature (a superseded value, the other Erik's number) zeroes it.
            r["wrong"] = [p for p in q.get("reject", []) if re.search(p, r["answer"], re.I)]
            if r["wrong"]:
                r["facts"] = 0.0
answer_runs = {k: v for k, v in qa.items() if v and v[0].get("mode") != "retrieval"}
retrieval_runs = {k: v for k, v in qa.items() if v and v[0].get("mode") == "retrieval"}

if answer_runs:
    out += ["## Q&A", "",
            "| Run | Model | Mode | Embedder | Facts | Abstain | Context | Files | Cited | Median s | Total min | tok/s |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for lab, rs in answer_runs.items():
        s, r0 = qa_summary(rs), rs[0]
        tok = "—" if s["tok_s"] is None else f"{s['tok_s']:.1f}"
        out.append(f"| {lab} | {r0.get('model', '?')} | {r0.get('mode', 'plain')} | {r0.get('embedder', '?')}"
                   f"{'' if r0.get('reranker', True) else ' (no rerank)'} | {pct(s['facts'])} | {pct(s['abstain'])} | "
                   f"{pct(s['context'])} | {pct(s['files'])} | {pct(s['cited'])} | "
                   f"{s['median_s']:.0f} | {s['total_min']:.1f} | {tok} |")
    out.append("")

    for field, title in (("domain", "Facts by domain"), ("kind", "Facts by question kind")):
        keys = sorted({r.get(field) or "?" for rs in answer_runs.values() for r in rs})
        out += [f"### {title}", "", "| Run | " + " | ".join(keys) + " |", "| --- | " + " | ".join("---" for _ in keys) + " |"]
        for lab, rs in answer_runs.items():
            cells = [pct(mean(r["facts"] for r in rs if (r.get(field) or "?") == k)) for k in keys]
            out.append(f"| {lab} | " + " | ".join(cells) + " |")
        out.append("")

    labels = list(answer_runs)
    first = max(answer_runs.values(), key=len)
    out += ["### Per question", "", "| Question | Kind | " + " | ".join(labels) + " |",
            "| --- | --- | " + " | ".join("---" for _ in labels) + " |"]
    by = {lab: {r["id"]: r for r in rs} for lab, rs in answer_runs.items()}
    for q in first:
        cells = []
        for lab in labels:
            r = by[lab].get(q["id"])
            cells.append("—" if r is None else pct(r["facts"]) + ("" if r["cited"] or r["kind"] == "unanswerable" else " ·nc"))
        out.append(f"| {q['id']}: {q['question'][:64]} | {q['kind']} | " + " | ".join(cells) + " |")
    out += ["", "`·nc` = no citation.", ""]

if retrieval_runs:
    out += ["## Search only (embedder comparison, no answer model)", "",
            "| Run | Embedder | Reranker | Context | Files | Median s |", "| --- | --- | --- | --- | --- | --- |"]
    for lab, rs in retrieval_runs.items():
        s, r0 = qa_summary(rs), rs[0]
        out.append(f"| {lab} | {r0.get('embedder', '?')} | {r0.get('rerankerModel') or ('on' if r0.get('reranker') else 'off')} | "
                   f"{pct(s['context'])} | {pct(s['files'])} | {s['median_s']:.1f} |")
    out.append("")

filing = load("filing")
# Re-check the place against the current filing.json (same reason as above).
CASES = {c["id"]: c for c in json.loads((HERE / "filing.json").read_text())}
for rs in filing.values():
    for r in rs:
        c = CASES.get(r["id"])
        if c and not r.get("error"):
            r["actionOK"] = r["action"] in c["expect_action"].split("|")
        if c and c["expect_action"] != "skip" and not r.get("error"):
            r["placeOK"] = r["action"] != "skip" and re.search(c["expect_path"], r["path"], re.I) is not None
            r["leaks"] = [x for x in c["forbid"] if re.search(x, r.get("markdown", ""), re.I)]
if filing:
    out += ["## Filing dropped documents", "",
            "| Run | Model | Action | Place | Facts kept | Leaks | Errors | Median s |",
            "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for lab, rs in filing.items():
        n = len(rs)
        out.append(f"| {lab} | {rs[0].get('model', '?')} | {pct(sum(r['actionOK'] for r in rs) / n)} | "
                   f"{pct(sum(r['placeOK'] for r in rs) / n)} | {pct(mean(r['facts'] for r in rs))} | "
                   f"{sum(len(r['leaks']) for r in rs)} | {sum(1 for r in rs if r.get('error'))} | "
                   f"{median(r['seconds'] for r in rs):.0f} |")
    out.append("")
    labels = list(filing)
    out += ["### Per document", "", "| Case | Expected | " + " | ".join(labels) + " |",
            "| --- | --- | " + " | ".join("---" for _ in labels) + " |"]
    byf = {lab: {r["id"]: r for r in rs} for lab, rs in filing.items()}
    for c in filing[labels[0]]:
        cells = []
        for lab in labels:
            r = byf[lab].get(c["id"])
            if r is None:
                cells.append("—")
            elif r.get("error"):
                cells.append("error")
            else:
                mark = "✓" if r["actionOK"] and r["placeOK"] else "✗"
                extra = f" leak×{len(r['leaks'])}" if r["leaks"] else ""
                cells.append(f"{mark} {r['action']} `{r['path'] or '—'}` {pct(r['facts'])}{extra}")
        out.append(f"| {c['id']}: {c['file']} | {c['expectAction']} | " + " | ".join(cells) + " |")
    out.append("")

(HERE / "report.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
