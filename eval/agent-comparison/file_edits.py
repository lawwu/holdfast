#!/usr/bin/env python3
"""Compare installed Pi file tools with Holdfast proposals on synthetic bytes.

Direct probes separate editor behavior from model mistakes. Optional model trials
use the same local Ollama weights/sampling, but each editor's actual tool schema.
"""
import argparse
import base64
import difflib
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import tempfile
import threading
import time

from run import HERE, ROOT, Proxy, api, bridge, execute, files, save, state_path, swift_calls

MARKER = "synthetic holdfast agent evaluation\n"
BASE = '# Notes\n\n- [ ] Renew policy\n\nKeep: “Café”—½\nHard break  \nnext line\n'


def encoded(value):
    if value is None:
        return None
    return {"text": value.decode("utf8"), "base64": base64.b64encode(value).decode(),
            "sha256": hashlib.sha256(value).hexdigest()}


def capture(vault):
    return {name: encoded(value) for name, value in files(vault).items()}


def proposals(state):
    result = []
    for path in sorted((state / "inbox").glob("*.md")):
        raw = path.read_bytes()
        assert raw.startswith(b"---\n")
        end = raw.index(b"\n---\n", 4)
        result.append({"id": "@inbox/" + path.stem, "raw": encoded(raw), "body": encoded(raw[end + 5:])})
    return result


def environment(vault, model):
    return {**os.environ, "HOLDFAST_VAULT": str(vault), "HOLDFAST_AGENT_EVAL": "1",
            "HOLDFAST_PACKS": "none", "HOLDFAST_EMBED": "none", "HOLDFAST_RERANK": "0",
            "HOLDFAST_THINK": "0", "HOLDFAST_TODAY": "2026-11-09", "HOLDFAST_REMOTE_MODEL": model}


def pi(args, env, artifact, vault, **operation):
    payload = {"piPackage": str(args.pi_package), "vault": str(vault), **operation}
    save(artifact / "pi-input.json", payload)
    process, elapsed = execute(["node", str(HERE / "pi-file-edits.mjs"), str(artifact / "pi-input.json")], env)
    (artifact / "pi-stderr.log").write_text(process.stderr)
    if process.returncode:
        raise RuntimeError(process.stderr)
    return json.loads(process.stdout.strip().splitlines()[-1]), elapsed


def approve(args, env, id):
    process, elapsed = execute([str(args.binary), "approve", id], env)
    return {"code": process.returncode, "stdout": process.stdout, "stderr": process.stderr, "seconds": elapsed}


def undo(args, env):
    process, elapsed = execute([str(args.binary), "undo", "1"], env)
    return {"code": process.returncode, "stdout": process.stdout, "stderr": process.stderr, "seconds": elapsed}


def direct_cases():
    def case(id, before=BASE, edits=None, **kw):
        return {"id": id, "path": "note.md", "before": before,
                "edits": edits or [("- [ ] Renew policy", "- [x] Renew policy")], **kw}
    return [
        case("exact-unicode"),
        case("ambiguous", before=BASE + "\n- [ ] Renew policy\n"),
        case("fuzzy-quotes", before=BASE.replace("Renew policy", "Review “Plan A”"),
             edits=[('- [ ] Review "Plan A"', '- [x] Review "Plan A"')]),
        case("bom-crlf", before="\ufeff" + BASE.replace("\n", "\r\n")),
        case("crlf-multiline", before=BASE.replace("\n", "\r\n"),
             edits=[("# Notes\n\n- [ ] Renew policy", "# Notes\n\n- [x] Renew policy")]),
        case("multiple", edits=[("- [ ] Renew policy", "- [x] Renew policy"), ("next line", "last line")]),
        case("batch-missing", edits=[("- [ ] Renew policy", "- [x] Renew policy"), ("missing text", "last line")], partial=True),
        case("generated", before="> GENERATED by scripts/report.py\n\n" + BASE),
        case("csv", before="item,status\npolicy,open\n", edits=[("policy,open", "policy,done")], path="data.csv"),
        case("new-file", before=None, write="# New note\n", edits=[("", "# New note\n")]),
        case("stale-unrelated", concurrent=BASE + "\nAdded by another writer.\n"),
        case("stale-target", concurrent=BASE.replace("Renew policy", "Renew different policy")),
        case("stale-whole-write", write=BASE.replace("- [ ]", "- [x]"),
             edits=[(BASE, BASE.replace("- [ ]", "- [x]"))], concurrent=BASE + "\nAdded by another writer.\n"),
        case("successive-approvals", edits=[("- [ ] Renew policy", "- [x] Renew policy"), ("next line", "last line")], successive=True)
    ]


def direct(args):
    rows = []
    for case in direct_cases():
        for arm in ["pi-native", "holdfast"]:
            artifact = args.out / (case["id"] + "-" + arm)
            artifact.mkdir()
            row = {"case": case["id"], "arm": arm, "input": case}
            with tempfile.TemporaryDirectory(prefix="holdfast-file-eval-", dir=Path.home() / ".cache") as temporary:
                vault = Path(temporary) / "vault"
                vault.mkdir()
                (vault / ".agent-eval-synthetic").write_text(MARKER)
                # Keep the new-file case an existing in-place vault too, rather
                # than triggering Holdfast's empty managed-vault initialization.
                (vault / "untouched.txt").write_bytes(b"Unrelated file.  \n")
                target = vault / case["path"]
                if case["before"] is not None:
                    target.write_bytes(case["before"].encode())
                before = files(vault)
                state = state_path(vault)
                assert not state.exists()
                env = environment(vault, args.model)
                row["before"] = capture(vault)
                try:
                    if arm == "holdfast":
                        config, _, _ = bridge(args.binary, env, {"op": "config"})
                        assert config["stateDir"] == str(state)
                    if case.get("successive"):
                        row["steps"] = []
                        for index, (old, new) in enumerate(case["edits"]):
                            if arm == "pi-native":
                                result, _ = pi(args, env, artifact, vault, direct=True, name="edit",
                                    arguments={"path": case["path"], "edits": [{"oldText": old, "newText": new}]})
                                step = {"tool": result}
                            else:
                                unchanged = files(vault)
                                result, _, _ = bridge(args.binary, env, {"op": "call", "name": "propose_edit",
                                    "arguments": {"path": case["path"], "old_text": old, "new_text": new}})
                                pending = proposals(state)
                                step = {"tool": result, "proposals": pending, "unchangedBeforeApproval": files(vault) == unchanged}
                                if len(pending) == 1:
                                    step["apply"] = approve(args, env, pending[0]["id"])
                            step["after"] = capture(vault)
                            row["steps"].append(step)
                            if index == 0:
                                row["expectedAfterUndo"] = capture(vault)
                        row["after"] = capture(vault)
                        if arm == "holdfast":
                            row["undo"] = undo(args, env)
                            row["afterUndo"] = capture(vault)
                            row["undoExact"] = row["afterUndo"] == row["expectedAfterUndo"]
                    elif arm == "pi-native":
                        # Simulate a stale model read. Pi's edit rereads at execution;
                        # write receives the old full content supplied by the caller.
                        if "concurrent" in case:
                            row["read"], _ = pi(args, env, artifact, vault, direct=True, name="read", arguments={"path": case["path"]})
                            target.write_bytes(case["concurrent"].encode())
                        row["atExecution"] = capture(vault)
                        if "write" in case:
                            name, arguments = "write", {"path": case["path"], "content": case["write"]}
                        else:
                            name, arguments = "edit", {"path": case["path"], "edits": [{"oldText": a, "newText": b} for a, b in case["edits"]]}
                        row["tool"], _ = pi(args, env, artifact, vault, direct=True, name=name, arguments=arguments)
                    else:
                        row["tools"] = []
                        for old, new in case["edits"]:
                            result, _, _ = bridge(args.binary, env, {"op": "call", "name": "propose_edit",
                                "arguments": {"path": case["path"], "old_text": old, "new_text": new, "why": "Synthetic editor comparison"}})
                            row["tools"].append(result)
                        row["unchangedBeforeApproval"] = files(vault) == before
                        row["proposals"] = proposals(state)
                        if "concurrent" in case:
                            target.write_bytes(case["concurrent"].encode())
                        row["atExecution"] = capture(vault)
                        # A partial multi-call proposal is evidence, not permission
                        # to apply an incomplete request.
                        if len(row["proposals"]) == 1 and not case.get("partial"):
                            row["apply"] = approve(args, env, row["proposals"][0]["id"])
                    row.setdefault("after", capture(vault))
                    original = case.get("concurrent", case["before"]) or ""
                    final = row["after"].get(case["path"], {}).get("text", "")
                    row["actualDiff"] = "".join(difflib.unified_diff(original.splitlines(keepends=True), final.splitlines(keepends=True), fromfile="before", tofile="after"))
                    if arm == "holdfast" and row.get("apply", {}).get("code") == 0:
                        row["undo"] = undo(args, env)
                        row["undoExact"] = files(vault) == before
                        row["afterUndo"] = capture(vault)
                except Exception as error:
                    row["runnerError"] = repr(error)
                finally:
                    row.setdefault("after", capture(vault))
                    if state.exists():
                        shutil.copytree(state, artifact / "state")
                        shutil.rmtree(state)
            save(artifact / "result.json", row)
            rows.append(row)
            save(args.out / "direct-results.json", rows)
            print(f"DIRECT {case['id']} {arm}: " + row.get("runnerError", "recorded"), flush=True)
    if any("runnerError" in row for row in rows):
        raise RuntimeError("A direct probe failed to execute; inspect direct-results.json")


FIXTURE = '''---
title: Quarterly checklist
owner: Alex
---
# Projects

## Home
- [ ] Renew policy
- [ ] Review “Plan A”

## Work
- [ ] Renew policy
- [ ] Update travel budget

## Later
- [ ] Book annual visit

Keep: “Café”—½
Hard break  
next line
'''


def model_cases():
    return [
        {"id": "repeated-item", "question": "In projects.md, mark 'Renew policy' as done only under Work. Keep the Home item and all other text, metadata and formatting unchanged.",
         "expected": FIXTURE.replace("## Work\n- [ ]", "## Work\n- [x]")},
        {"id": "insert-section", "question": "In projects.md, add the open item 'Check HSA beneficiary' as the last checklist item under Work, before Later. Preserve all existing content, metadata and formatting.",
         "item": "- [ ] Check HSA beneficiary"},
        {"id": "two-edits", "question": "In projects.md, mark Review “Plan A” under Home as done and change 'Book annual visit' to 'Book annual visit with Alex' under Later. Preserve everything else, including metadata and formatting.",
         "expected": FIXTURE.replace('- [ ] Review “Plan A”', '- [x] Review “Plan A”').replace("Book annual visit", "Book annual visit with Alex")}
    ]


def models(args):
    show = api("/api/show", {"model": args.model})
    if show.get("remote_model") or show.get("remote_host") or ":cloud" in args.model:
        raise ValueError("A downloaded local model is required")
    if api("/api/ps").get("models"):
        raise RuntimeError("Ollama has a loaded model; avoid disturbing another workload")
    rows = []
    for index, task in enumerate(model_cases()):
        for arm in (["pi-native", "holdfast"] if index % 2 == 0 else ["holdfast", "pi-native"]):
            artifact = args.out / (task["id"] + "-" + arm)
            artifact.mkdir()
            row = {"task": task["id"], "arm": arm, "question": task["question"]}
            print(f"START {task['id']} {arm}", flush=True)
            with tempfile.TemporaryDirectory(prefix="holdfast-file-eval-", dir=Path.home() / ".cache") as temporary:
                vault = Path(temporary) / "vault"
                vault.mkdir()
                (vault / ".agent-eval-synthetic").write_text(MARKER)
                (vault / "projects.md").write_bytes(FIXTURE.encode())
                (vault / "untouched.txt").write_bytes(b"Unrelated file.  \n")
                before = files(vault)
                row["before"] = capture(vault)
                state = state_path(vault)
                assert not state.exists()
                env = environment(vault, args.model)
                proxy = Proxy(args.model, 43)
                thread = threading.Thread(target=proxy.serve_forever, daemon=True)
                thread.start()
                env["HOLDFAST_REMOTE_URL"] = f"http://127.0.0.1:{proxy.server_port}"
                try:
                    warm = api("/api/chat", {"model": args.model, "messages": [{"role": "user", "content": "Hello."}],
                        "stream": False, "think": False, "keep_alive": "15m", "options": {"num_predict": 1, "num_ctx": 32768}})
                    row["warmupSeconds"] = warm.get("total_duration", 0) / 1e9
                    if arm == "pi-native":
                        result, elapsed = pi(args, env, artifact, vault, baseUrl=env["HOLDFAST_REMOTE_URL"] + "/v1",
                            model=args.model, question=task["question"], agentDir=temporary + "/pi",
                            transcript=str((artifact / "pi-transcript.json").resolve()))
                    else:
                        result, elapsed, stderr = bridge(args.binary, env, {"op": "run", "engine": "ollama", "question": task["question"]})
                        (artifact / "swift-stderr.log").write_text(stderr)
                        result["calls"] = swift_calls(state)
                    row.update(result, processSeconds=elapsed)
                    checks = {}
                    if arm == "holdfast":
                        checks["unchangedBeforeApproval"] = files(vault) == before
                        row["proposals"] = proposals(state)
                        checks["oneProposal"] = len(row["proposals"]) == 1
                        checks["approvalExplained"] = bool(re.search(r"inbox|approv|pending", row["answer"], re.I))
                        if checks["oneProposal"]:
                            row["apply"] = approve(args, env, row["proposals"][0]["id"])
                            checks["applySucceeded"] = row["apply"]["code"] == 0
                    row["after"] = capture(vault)
                    actual = (vault / "projects.md").read_bytes()
                    if "expected" in task:
                        checks["exactRequestedEdit"] = actual == task["expected"].encode()
                    else:
                        item = task["item"] + "\n"
                        text = actual.decode()
                        checks["itemOnceInWork"] = text.count(item) == 1 and text.index("## Work") < text.find(item) < text.index("## Later")
                        # Allow blank lines around the insertion, preserving ALL
                        # nonblank lines including trailing Markdown hard breaks.
                        checks["existingLinesExact"] = [line for line in text.replace(item, "").splitlines() if line] == [line for line in FIXTURE.splitlines() if line]
                    checks["otherFilesExact"] = {k: v for k, v in files(vault).items() if k != "projects.md"} == {k: v for k, v in before.items() if k != "projects.md"}
                    if arm == "holdfast" and row.get("apply", {}).get("code") == 0:
                        row["undo"] = undo(args, env)
                        checks["undoExact"] = row["undo"]["code"] == 0 and files(vault) == before
                    row["checks"] = checks
                    row["passed"] = all(checks.values()) and not proxy.failures
                except Exception as error:
                    row.update(runnerError=repr(error), passed=False)
                finally:
                    row.setdefault("after", capture(vault))
                    proxy.shutdown()
                    proxy.server_close()
                    save(artifact / "requests.json", proxy.records)
                    if proxy.failures:
                        row["proxyFailures"] = proxy.failures
                    if state.exists():
                        shutil.copytree(state, artifact / "state")
                        shutil.rmtree(state)
                    api("/api/generate", {"model": args.model, "keep_alive": 0})
            save(artifact / "result.json", row)
            rows.append(row)
            save(args.out / "model-results.json", rows)
            print(f"END {task['id']} {arm}: {'PASS' if row['passed'] else 'FAIL'} {row.get('loopSeconds', 0):.1f}s " + row.get("runnerError", ""), flush=True)
    if any(not row.get("passed") for row in rows):
        raise SystemExit(1)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--binary", type=Path, default=ROOT / ".build/harness-xcode/Build/Products/Release/holdfast")
    parser.add_argument("--model", default="qwen38-27b-q8-32k:latest")
    parser.add_argument("--mode", choices=["direct", "models"], default="direct")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    args.binary = args.binary.resolve()
    args.pi_package = Path(shutil.which("pi")).resolve().parents[1]
    args.out = args.out.resolve()
    args.out.mkdir(parents=True, exist_ok=False)
    (Path.home() / ".cache").mkdir(exist_ok=True)
    save(args.out / "metadata.json", {"created": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "mode": args.mode,
        "model": args.model, "piVersion": json.loads((args.pi_package / "package.json").read_text())["version"],
        "binarySHA256": hashlib.sha256(args.binary.read_bytes()).hexdigest(),
        "note": "Same local Ollama weights/sampling for model trials. Different editor schemas and suitable system prompts; not a harness-only comparison. Stock Pi tools, no checkpoint/approval extensions; guarded scratch operations supplied by evaluation."})
    (direct if args.mode == "direct" else models)(args)


if __name__ == "__main__":
    main()
